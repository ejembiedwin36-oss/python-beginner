# how to writ a function with two variable 
def add_num(a, b):
    return a + b
result = add_num(5 ,3)
print(result)

# function whit 3 variable 
def multiple_num(a, b, c):
    return a + b + c
res = multiple_num(10, 5, 5)
print(res)

# multiplication
def multiply_num(a, b):
    return a * b
ans = multiply_num(3, 9)
print(ans)

# subtraction
def subtract_num(c, b):
    return c - b
answer = subtract_num(30, 10)
print(answer)

# division
def divide_num(a, c):
    return a / c
rest = divide_num(30, 2)
print(rest)



