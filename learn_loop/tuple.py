# In Python, a tuple is a fixed, unchangeable list of items locked inside parentheses.
# remember you can not change, add, update even remove an item.
tup = ("Ejembi", "john", "Friday", "oko")
print(tup)
print(tup[0])
print(tup[1])
print(tup[2])
print(tup[3])
print(tup[::-1])

for i, x,in  enumerate(tup):
    print(i, x)



